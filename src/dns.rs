use std::fs;
use std::net::{IpAddr, SocketAddr};
use std::sync::Mutex;
use std::time::{Duration, Instant};

use crate::{log_debug, log_info};

const DNS_REFRESH_INTERVAL: Duration = Duration::from_secs(2);

struct DnsState {
    cached: Option<SocketAddr>,
    last_checked: Option<Instant>,
}

/// Thread-safe system DNS resolver cache (reads `/etc/resolv.conf`, refreshed every 2 seconds,
/// matching `maybe_update_dns()` in BadVPN).
pub struct SystemDns {
    state: Mutex<DnsState>,
}

impl SystemDns {
    pub fn new() -> Self {
        let resolver = Self {
            state: Mutex::new(DnsState {
                cached: None,
                last_checked: None,
            }),
        };
        let _ = resolver.get_server();
        resolver
    }

    pub fn get_server(&self) -> Option<SocketAddr> {
        let mut guard = self.state.lock().unwrap_or_else(|e| e.into_inner());
        let now = Instant::now();
        if let Some(last) = guard.last_checked {
            if now.duration_since(last) < DNS_REFRESH_INTERVAL {
                return guard.cached;
            }
        }
        guard.last_checked = Some(now);
        log_debug!("updating system DNS from /etc/resolv.conf");

        let parsed = read_resolv_conf("/etc/resolv.conf");
        if parsed != guard.cached {
            if let Some(addr) = parsed {
                log_info!("using DNS server {}", addr);
            }
        }
        guard.cached = parsed;
        guard.cached
    }
}

impl Default for SystemDns {
    fn default() -> Self {
        Self::new()
    }
}

pub fn parse_resolv_conf(content: &str) -> Option<SocketAddr> {
    for line in content.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') || trimmed.starts_with(';') {
            continue;
        }
        let mut parts = trimmed.split_whitespace();
        if let (Some("nameserver"), Some(ip_str)) = (parts.next(), parts.next()) {
            // Strip optional IPv6 zone identifier if present.
            let clean_ip = ip_str.split('%').next().unwrap_or(ip_str);
            if let Ok(ip) = clean_ip.parse::<IpAddr>() {
                return Some(SocketAddr::new(ip, 53));
            }
        }
    }
    None
}

fn read_resolv_conf(path: &str) -> Option<SocketAddr> {
    let content = fs::read_to_string(path).ok()?;
    parse_resolv_conf(&content)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_first_nameserver() {
        let conf = "\
# Generated by resolvconf
search example.com
nameserver 1.1.1.1
nameserver 8.8.8.8
";
        assert_eq!(
            parse_resolv_conf(conf),
            Some("1.1.1.1:53".parse().unwrap())
        );
    }

    #[test]
    fn parses_ipv6_nameserver() {
        let conf = "nameserver 2606:4700:4700::1111\n";
        assert_eq!(
            parse_resolv_conf(conf),
            Some("[2606:4700:4700::1111]:53".parse().unwrap())
        );
    }
}
